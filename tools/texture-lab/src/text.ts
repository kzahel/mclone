import { drawRect, type Rgba, type RgbaImage } from "./image";

export function drawPixelText(target: RgbaImage, text: string, x: number, y: number, scale: number, color: Rgba): void {
  let cursorX = x;
  for (const character of text.toUpperCase()) {
    const glyph = PIXEL_FONT[character] ?? PIXEL_FONT[" "];
    if (!glyph) {
      cursorX += 6 * scale;
      continue;
    }
    for (let gy = 0; gy < glyph.length; gy += 1) {
      const row = glyph[gy]!;
      for (let gx = 0; gx < row.length; gx += 1) {
        if (row[gx] === "1") {
          drawRect(target, cursorX + gx * scale, y + gy * scale, scale, scale, color);
        }
      }
    }
    cursorX += 6 * scale;
  }
}

export function textPixelWidth(text: string, scale: number): number {
  return Math.max(0, text.length * 6 * scale - scale);
}

export function pad3(value: number): string {
  return Math.max(0, Math.min(999, Math.round(value))).toString().padStart(3, "0");
}

